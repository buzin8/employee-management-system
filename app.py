def connect_db():
    if DATABASE_URL:
        return psycopg.connect(DATABASE_URL, row_factory=dict_row)
    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    return conn


def adapt_sql(sql, params):
    if DATABASE_URL:
        sql = sql.replace("?", "%s")
        if isinstance(params, dict):
            sql = re.sub(r"(?<!:):([A-Za-z_]\w*)", r"%(\1)s", sql)
    return sql


def execute(sql, params=()):
    return db().execute(adapt_sql(sql, params), params)


def db():
    if "db" not in g:
        g.db = connect_db()
    return g.db


@app.teardown_appcontext
def close_db(_):
    conn = g.pop("db", None)
    if conn:
        conn.close()


def init_db():
    conn = connect_db()
    try:
        if DATABASE_URL:
            for statement in POSTGRES_SCHEMA.split(";"):
                if statement.strip():
                    conn.execute(statement)
        else:
            conn.executescript(SCHEMA)
        if conn.execute("SELECT COUNT(*) AS total FROM employees").fetchone()["total"] == 0:
            conn.cursor().executemany(
                adapt_sql(
                    "INSERT INTO employees (name,email,phone,department,designation,salary,join_date) VALUES (?,?,?,?,?,?,?)",
                    SEED,
                ),
                SEED,
            )
        conn.commit()
    finally:
        conn.close()


def validate(form, emp_id=None):
    data = {k: form.get(k, "").strip() for k in ("name", "email", "phone", "department", "designation", "salary", "join_date")}
    errors = []
    if not data["name"]:
        errors.append("Enter the employee's name.")
    if not re.match(r"^[^@\s]+@[^@\s]+\.[^@\s]+$", data["email"]):
        errors.append("Enter a valid email address.")
    if data["phone"] and not re.match(r"^[0-9+\-\s]{7,15}$", data["phone"]):
        errors.append("Phone can contain digits, +, - and spaces (7 to 15 characters).")
    if data["department"] not in DEPARTMENTS:
        errors.append("Choose a department.")
    if not data["designation"]:
        errors.append("Choose a designation.")
    elif emp_id is None and data["designation"] not in DESIGNATIONS.get(data["department"], []):
        errors.append("Choose a designation for the selected department.")
    try:
        if float(data["salary"]) <= 0:
            raise ValueError
    except ValueError:
        errors.append("Salary must be a number greater than 0.")
    if not data["join_date"]:
        errors.append("Choose a join date.")
    if data["email"] and not errors:
        duplicate_query = "SELECT id FROM employees WHERE email=?"
        duplicate_params = (data["email"],)
        if emp_id is not None:
            duplicate_query += " AND id != ?"
            duplicate_params += (emp_id,)
        row = execute(duplicate_query, duplicate_params).fetchone()
        if row:
            errors.append("Another employee already uses this email.")
    if data["phone"] and re.fullmatch(r"[0-9+\-\s]{7,15}", data["phone"]):
        phone_digits = re.sub(r"\D", "", data["phone"])
        existing_phones = execute(
            "SELECT id, phone FROM employees WHERE phone IS NOT NULL AND phone != ''"
        ).fetchall()
        if any(
            row["id"] != emp_id
            and re.sub(r"\D", "", row["phone"]) == phone_digits
            for row in existing_phones
        ):
            errors.append("Another employee already uses this phone number.")
    return data, errors


@app.route("/")
def index():
    q = request.args.get("q", "").strip()
    dept = request.args.get("dept", "")
    sort = request.args.get("sort", "name")
    page = max(int(request.args.get("page", 1) or 1), 1)
    where, args = [], []
    if q:
        where.append("(LOWER(name) LIKE LOWER(?) OR LOWER(email) LIKE LOWER(?) OR LOWER(phone) LIKE LOWER(?) OR LOWER(department) LIKE LOWER(?) OR LOWER(designation) LIKE LOWER(?))")
        args += [f"%{q}%"] * 5
    if dept:
        where.append("department = ?")
        args.append(dept)
    clause = ("WHERE " + " AND ".join(where)) if where else ""
    total_found = execute(
        f"SELECT COUNT(*) AS total FROM employees {clause}", args
    ).fetchone()["total"]
    pages = max((total_found + PER_PAGE - 1) // PER_PAGE, 1)
    page = min(page, pages)
    rows = execute(
        f"SELECT * FROM employees {clause} ORDER BY {SORTS.get(sort, 'name')} LIMIT ? OFFSET ?",
        args + [PER_PAGE, (page - 1) * PER_PAGE]).fetchall()
    stats_query = (
        "SELECT COUNT(*) c, COALESCE(AVG(salary),0) a, COALESCE(SUM(salary),0) s, "
        "COALESCE(MAX(salary),0) m, COUNT(DISTINCT department) d, "
        "COUNT(*) FILTER (WHERE join_date >= date_trunc('year', CURRENT_DATE)::date) n "
        "FROM employees"
        if DATABASE_URL else
        "SELECT COUNT(*) c, COALESCE(AVG(salary),0) a, COALESCE(SUM(salary),0) s, "
        "COALESCE(MAX(salary),0) m, COUNT(DISTINCT department) d, "
        "COALESCE(SUM(join_date >= date('now','start of year')),0) n FROM employees"
    )
    stats = execute(stats_query).fetchone()
    top = execute("SELECT name, designation, salary FROM employees ORDER BY salary DESC LIMIT 4").fetchall()
    by_dept = execute("SELECT department, COUNT(*) c FROM employees GROUP BY department ORDER BY c DESC").fetchall()
    return render_template("index.html", rows=rows, q=q, dept=dept, sort=sort, page=page, pages=pages,
                           found=total_found, total=stats["c"], avg=stats["a"], stats=stats, top=top, by_dept=by_dept, departments=DEPARTMENTS)


@app.route("/employee/<int:emp_id>")
def employee_detail(emp_id):
    employee = execute("SELECT * FROM employees WHERE id=?", (emp_id,)).fetchone()
    if not employee:
        abort(404)
    return render_template("employee.html", employee=employee)


@app.route("/add", methods=["GET", "POST"])
def add():
    data = {}
    if request.method == "POST":
        data, errors = validate(request.form)
        if not errors:
            execute("INSERT INTO employees (name,email,phone,department,designation,salary,join_date) VALUES (:name,:email,:phone,:department,:designation,:salary,:join_date)", data)
            db().commit()
            flash(f"Added {data['name']}.")
            return redirect(url_for("index"))
        for e in errors:
            flash(e, "error")
    return render_template("form.html", e=data, departments=DEPARTMENTS, designations=DESIGNATIONS, mode="Add")


@app.route("/edit/<int:emp_id>", methods=["GET", "POST"])
def edit(emp_id):
    emp = execute("SELECT * FROM employees WHERE id=?", (emp_id,)).fetchone()
    if not emp:
        abort(404)
    data = dict(emp)
    if request.method == "POST":
        data, errors = validate(request.form, emp_id)
        if not errors:
            data["id"] = emp_id
            execute("UPDATE employees SET name=:name,email=:email,phone=:phone,department=:department,designation=:designation,salary=:salary,join_date=:join_date,updated_at=CURRENT_TIMESTAMP WHERE id=:id", data)
            db().commit()
            flash(f"Saved changes for {data['name']}.")
            return redirect(url_for("index"))
        for e in errors:
            flash(e, "error")
    return render_template("form.html", e=data, departments=DEPARTMENTS, designations=DESIGNATIONS, mode="Edit")


@app.route("/delete/<int:emp_id>", methods=["POST"])
def delete(emp_id):
    execute("DELETE FROM employees WHERE id=?", (emp_id,))
    db().commit()
    flash("Employee deleted.")
    return redirect(url_for("index"))


@app.route("/export.csv")
def export():
    fields = ["id", "name", "email", "phone", "department", "designation", "salary", "join_date"]
    rows = execute(f"SELECT {','.join(fields)} FROM employees ORDER BY name").fetchall()
    out = io.StringIO()
    w = csv.writer(out)
    w.writerow(fields)
    w.writerows([[row[field] for field in fields] for row in rows])
    return Response(out.getvalue(), mimetype="text/csv", headers={"Content-Disposition": "attachment; filename=employees.csv"})


